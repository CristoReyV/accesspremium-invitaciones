// Obtener plantilla por ID
export function getInvitationById(id: string): InvitationTemplate | undefined {
  return INVITATIONS.find((inv) => inv.id === id);
}

// Obtener plantilla por slug
export function getInvitationBySlug(slug: string): InvitationTemplate | undefined {
  return INVITATIONS.find((inv) => inv.slug === slug);
}

// Filtrar por categoría
export function getInvitationsByCategory(
  category: InvitationTemplate["category"]
): InvitationTemplate[] {
  return INVITATIONS.filter((inv) => inv.category === category);
}

// Obtener solo las del MVP
export function getMVPInvitations(): InvitationTemplate[] {
  return INVITATIONS.filter((inv) => inv.priority === "mvp");
}

// Obtener plantillas destacadas para la landing (badge popular o mvp)
export function getFeaturedInvitations(limit = 9): InvitationTemplate[] {
  return INVITATIONS.filter(
    (inv) => inv.badge === "popular" || inv.priority === "mvp"
  ).slice(0, limit);
}

// Filtrar por familia visual
export function getInvitationsByFamily(
  family: InvitationTemplate["family"]
): InvitationTemplate[] {
  return INVITATIONS.filter((inv) => inv.family === family);
}
